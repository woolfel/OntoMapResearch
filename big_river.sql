-- =====================================================================
-- BigRiver - Source Schema
-- Dialect: SQLite 3
--
-- Naming style: UPPER_SNAKE_CASE with a short table prefix on every column
--   (SC_ = ShoppingCart, ITM_ = Item, STR_ = Store, PRD_ = Product,
--    PRM_ = Promotions, TAG_ = ProductTags). SQLite treats unquoted names
--   case-insensitively but stores them as written, unlike Postgres,
--   which folds them to lower case -- a discussion point on its own.
-- Modeling habits (on purpose, for the lesson):
--   * Marketplace: many third-party Stores sell the same Product, so price
--     lives on the Item line and the Store, not on the Product.
--   * Surrogate keys are UUIDs (stored as TEXT).
--   * Timestamps are TIMESTAMP columns named *_DATE, stored in UTC as
--     'YYYY-MM-DD HH:MM:SS'. Open-ended end dates use '9999-12-31 23:59:59'
--     instead of NULL (PRM_END_DATE is NOT NULL).
--   * Multi-currency: amounts are NUMERIC with a separate currency column.
--   * Discount percentages are stored as fractions (0.15 = 15%).
--   * No brand table: brand is a plain text column on Product, and extra
--     attributes (color, size, "eco-friendly") live in key/value ProductTags.
--   * A cart can hold items from several stores; one promo per item line,
--     plus an optional cart-level coupon.
-- =====================================================================
--
-- SQLite notes: no BOOLEAN type (flags are INTEGER 0/1). SQLite has no
-- native timestamp type either: TIMESTAMP is accepted as a declared type
-- and the values are stored as ISO-8601 text, which sorts and compares
-- correctly and works with SQLite's date/time functions
-- (CURRENT_TIMESTAMP = UTC 'YYYY-MM-DD HH:MM:SS'). VARCHAR/NUMERIC sizes
-- are documentation only, not enforced.
-- Foreign keys are only enforced when PRAGMA foreign_keys = ON.

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS ITEM;
DROP TABLE IF EXISTS SHOPPING_CART;
DROP TABLE IF EXISTS PROMOTIONS;
DROP TABLE IF EXISTS PRODUCT_TAGS;
DROP TABLE IF EXISTS PRODUCT;
DROP TABLE IF EXISTS STORE;

-- ---------------------------------------------------------------------
-- STORE: a seller on the BigRiver marketplace
-- ---------------------------------------------------------------------
CREATE TABLE STORE (
    STR_UUID                TEXT          NOT NULL PRIMARY KEY,  -- UUID is the enterprise standard
    STR_HANDLE              VARCHAR(60)   NOT NULL UNIQUE,   -- 'gadget-galaxy'
    STR_DISPLAY_NAME        VARCHAR(150)  NOT NULL,
    STR_IS_FIRST_PARTY      INTEGER       NOT NULL DEFAULT 0,  -- sold by BigRiver itself
    STR_COUNTRY_ISO         CHAR(2)       NOT NULL,
    STR_DEFAULT_CCY         CHAR(3)       NOT NULL,          -- 'USD','CAD','EUR'
    STR_RATING              NUMERIC(2,1)  NULL,              -- 0.0 - 5.0
    STR_ONBOARDED_DATE      TIMESTAMP     NOT NULL,          -- when the seller joined the marketplace
    STR_STATUS              VARCHAR(12)   NOT NULL,          -- 'LIVE','SUSPENDED','CLOSED'
    STR_DRP_SHP_REGION      VARCHAR(50)   NULL,              -- 'US-NJ', 'CA-ON'
    STR_EFF_DATE            TIMESTAMP     NOT NULL,          -- the timestamp of when the store is effective
    STR_EXP_DATE            TIMESTAMP     NULL,              -- the timestamp of when the store is no longer effective
    STR_FBBR                INTEGER       NOT NULL DEFAULT 0   -- Fulfilled By BigRiver
);

-- ---------------------------------------------------------------------
-- PRODUCT: the catalog entry shared by every store that sells it
-- ---------------------------------------------------------------------
CREATE TABLE PRODUCT (
    PRD_UUID                TEXT          NOT NULL PRIMARY KEY,       -- UUID is the enterprise standard
    PRD_ID                  VARCHAR(16)   NOT NULL UNIQUE,   -- BigRiver Number is generated by the frontend UI and follows a standard convention
    PRD_NAME                VARCHAR(200)  NOT NULL,          -- product name used to display the item in search results and shopping cart
    PRD_LONG_NAME           VARCHAR(500)  NULL,              -- product name used to display the item on the product detail page
    PRD_BRAND_TEXT          VARCHAR(100)  NULL,              -- typed by sellers: 'Sony', 'SONY', 'Sony Electronics'
    PRD_MFR_PART_NO         VARCHAR(60)   NULL,              -- closest thing to a model number
    PRD_UPC                 VARCHAR(14)   NULL,              -- may be missing for unbranded goods or renewed/refurbished items
    PRD_CNTRY_ORGN          VARCHAR(2)    NULL,              -- ISO 3166 alpha-2
    PRD_BROWSE_PATH         VARCHAR(255)  NULL,              -- 'electronics>television>oled'
    PRD_WEIGHT_GRAMS        INTEGER       NULL,
    PRD_IS_ADULT            INTEGER       NOT NULL DEFAULT 0,
    PRD_IS_ACTIVE           INTEGER       NOT NULL DEFAULT 1
);

-- ---------------------------------------------------------------------
-- PRODUCT_TAGS: key/value attributes (EAV pattern)
-- ---------------------------------------------------------------------
CREATE TABLE PRODUCT_TAGS (
    TAG_ID                  INTEGER       PRIMARY KEY AUTOINCREMENT,
    TAG_PRD_UUID            TEXT          NOT NULL REFERENCES PRODUCT (PRD_UUID), -- the tag has to be associated with a product
    TAG_KEY                 VARCHAR(50)   NOT NULL,          -- 'color','screen_size','warranty','eco'
    TAG_VALUE               VARCHAR(255)  NOT NULL,          -- '65 in', '1 year limited', 'true'
    TAG_SOURCE              VARCHAR(10)   NOT NULL,          -- 'SELLER','BRAND','ML' (machine-inferred)
    TAG_CONFIDENCE          NUMERIC(3,2)  NULL,              -- only set when TAG_SOURCE = 'ML'
    TAG_CREATED_DATE        TIMESTAMP     NOT NULL           -- when the tag was added
);

-- ---------------------------------------------------------------------
-- PROMOTIONS: store-funded or platform-funded deals
-- ---------------------------------------------------------------------
CREATE TABLE PROMOTIONS (
    PRM_UUID                TEXT          NOT NULL PRIMARY KEY,       -- UUID is the enterprise standard
    PRM_COUPON_CODE         VARCHAR(25)   NULL,              -- NULL = automatic "lightning deal"
    PRM_LABEL               VARCHAR(150)  NOT NULL,          -- the short title of the promotion, like 15% off
    PRM_FUNDED_BY           VARCHAR(10)   NOT NULL,          -- 'PLATFORM' or 'STORE'
    PRM_STR_UUID            TEXT          NULL REFERENCES STORE (STR_UUID),  -- set when store-funded
    PRM_SCOPE               VARCHAR(12)   NOT NULL,          -- 'SITEWIDE','PRODUCT','TAG','CART'
    PRM_TARGET_PRD_UUID     TEXT          NULL REFERENCES PRODUCT (PRD_UUID),  -- the promotion can be applied to a specific product
    PRM_TARGET_TAG_KEY      VARCHAR(50)   NULL,              -- e.g. promo on all items tagged eco=true
    PRM_TARGET_TAG_VALUE    VARCHAR(255)  NULL,
    PRM_PCT_OFF             NUMERIC(4,3)  NULL,              -- 0.150 means 15%
    PRM_AMT_OFF             NUMERIC(10,2) NULL,              -- the amount off the product price
    PRM_AMT_CCY             CHAR(3)       NULL,              -- the currency of the amount off
    PRM_BUY_QTY             SMALLINT      NULL,              -- "buy 2 get 1": BUY=2, GET=1
    PRM_GET_QTY             SMALLINT      NULL,
    PRM_START_DATE          TIMESTAMP     NOT NULL,          -- the timestamp of when the promotion is effective
    PRM_END_DATE            TIMESTAMP     NOT NULL,          -- the timestamp of when the promotion is no longer effective; '9999-12-31 23:59:59' = open-ended
    PRM_MAX_REDEMPTIONS     INTEGER       NULL
);

-- ---------------------------------------------------------------------
-- SHOPPING_CART: one cart per customer session
-- ---------------------------------------------------------------------
CREATE TABLE SHOPPING_CART (
    SC_UUID                 TEXT          NOT NULL PRIMARY KEY,  -- UUID is the enterprise standard
    SC_ACCOUNT_ID           VARCHAR(36)   NULL,              -- NULL for guest checkout, otherwise the account ID
    SC_SESSION_TOKEN        VARCHAR(64)   NOT NULL,
    SC_CUSTOMER_EMAIL       VARCHAR(255)  NOT NULL,          -- the email that owns the cart; required, including for guest checkout
    SC_STATE                VARCHAR(15)   NOT NULL,          -- 'ACTIVE','SAVED_FOR_LATER','PURCHASED','EXPIRED'
    SC_CART_PRM_UUID        TEXT          NULL REFERENCES PROMOTIONS (PRM_UUID),  -- cart-level coupon
    SC_DISPLAY_CCY          CHAR(3)       NOT NULL,          -- currency the shopper saw
    SC_DEVICE               VARCHAR(10)   NULL,              -- 'IOS','ANDROID','DESKTOP','ALEXA'
    SC_CREATED_DATE         TIMESTAMP     NOT NULL,          -- when the cart was created
    SC_UPDATED_DATE         TIMESTAMP     NOT NULL,          -- when the cart was last changed
    SC_PURCHASED_DATE       TIMESTAMP     NULL,              -- when the cart was purchased; NULL until SC_STATE = 'PURCHASED'
    SC_SHIP_REGION          VARCHAR(50)   NULL               -- 'US-NJ', 'CA-ON'
);

-- ---------------------------------------------------------------------
-- ITEM: one product from one store in a cart
-- ---------------------------------------------------------------------
CREATE TABLE ITEM (
    ITM_UUID                TEXT          NOT NULL PRIMARY KEY,
    ITM_SC_UUID             TEXT          NOT NULL REFERENCES SHOPPING_CART (SC_UUID),
    ITM_PRD_UUID            TEXT          NOT NULL REFERENCES PRODUCT (PRD_UUID),
    ITM_STR_UUID            TEXT          NOT NULL REFERENCES STORE (STR_UUID),
    ITM_QTY                 INTEGER       NOT NULL CHECK (ITM_QTY > 0),
    ITM_OFFER_PRICE         NUMERIC(12,2) NOT NULL,          -- in ITM_PRICE_CCY
    ITM_PRICE_CCY           CHAR(3)       NOT NULL,          -- may differ from SC_DISPLAY_CCY
    ITM_FX_RATE_TO_USD      NUMERIC(12,6) NULL,              -- captured at add-to-cart time
    ITM_PRM_UUID            TEXT          NULL REFERENCES PROMOTIONS (PRM_UUID), -- if the item had a promotion applied to it
    ITM_PRM_SAVINGS         NUMERIC(12,2) NOT NULL DEFAULT 0, -- how much the promotion saved
    ITM_IS_SUBSCRIBE_SAVE   INTEGER       NOT NULL DEFAULT 0, -- if the item is part of a subscribe & save program
    ITM_IS_GIFT             INTEGER       NOT NULL DEFAULT 0,
    ITM_GIFT_MSG            VARCHAR(500)  NULL,
    ITM_GIFT_WRAP           INTEGER       NOT NULL DEFAULT 0,
    ITM_ADDED_DATE          TIMESTAMP     NOT NULL           -- when the item was added to the cart
);
